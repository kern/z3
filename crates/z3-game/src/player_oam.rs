    #[test]
    fn most_significant_bit_matches_65816_loop() {
        assert_eq!(find_most_significant_bit(0), 0xff);
        assert_eq!(find_most_significant_bit(1), 0);
        assert_eq!(find_most_significant_bit(0x24), 5);
        assert_eq!(find_most_significant_bit(0x80), 7);
    }

    #[test]
    fn sword_hitbox_uses_tip_then_normal_tables() {
        let mut bytes = [0; WRAM_SIZE];
        let mut ram = Ram::new(&mut bytes);
        ram.write_u8(0xf359, 2);
        ram.write_u8(0x2f, 0);
        ram.write_u8(0x3c, 2);
        calculate_sword_hit_box(&mut ram);
        assert_eq!((ram.read_i8(0x45), ram.read_i8(0x44)), (15, -5));
        ram.write_u8(0xf359, 1);
        ram.write_u8(0x3c, 10);
        calculate_sword_hit_box(&mut ram);
        assert_eq!((ram.read_i8(0x45), ram.read_i8(0x44)), (-3, -3));
    }

